/** System-wide figures, visible only to platform staff. */
export interface PlatformDashboard {
  companies: {
    total: number;
    trial: number;
    active: number;
    suspended: number;
  };
  users: {
    /** Every tenant user across every company. */
    total: number;
    admins: number;
    active: number;
    /** Created but never signed in, or holding an admin-set password. */
    pending: number;
    disabled: number;
  };
  /** Platform operators, not tenant users. */
  platformUsers: {
    total: number;
    active: number;
  };
  activity: {
    signInsLast24h: number;
    companiesCreatedLast30d: number;
    /** Newest first. */
    recent: PlatformActivityItem[];
  };
  health: {
    databaseStatus: 'up' | 'down';
    databaseLatencyMs: number | null;
    /** Total rows in the tenant audit trail — a rough activity measure. */
    auditRecordCount: number;
  };
}

export interface PlatformActivityItem {
  action: string;
  entityType: string;
  entityId: string | null;
  actor: string | null;
  at: string;
}

